<h1>Self-Hosting</h1>
<p>
Hier erfährst du, wie du deinen eigenen Minecraft-Walo Server hosten kannst!
</p>

<h2>Installiere das Minecraft-Walo Plugin</h2>

<p>
Am einfachsten ladest du dir einfach dieses Server-Paket runter: <a href="/assets/server-package/walo-server-package.zip">walo-server-package.zip</a>
</p>

<p>
Es ist ein vorkonfigurierter Server mit:
</p>

<ul class="list">
    <li><b>Paper 1.8.8</b> mit <a href="https://docs.papermc.io/paper/anti-xray">Anti-XRay Modus 2</a></li>
    <li><b>TerrainControl</b> so eingerichtet, dass keine Ozeane mehr Spawnen</li>
    <li>Dem <a href="/plugin.php">Walo</a>-Plugin</li>
    <li><b>WaloRestartCompanion</b>, was den Server automatisch neustartet, wenn das Spiel zuende ist</li>
    <li><b>DamageIndicator deaktiviert</b> für LabyMod</li>
    <li>Mit einem <b>Spielerlimit von 50</b></li>
</ul>

<h2>Server starten</h2>
<p>
Nach dem Herunterladen muss man die .zip Datei nurnoch extrahieren, die <b>eula.txt</b> akzeptieren und <b>start.bat</b> (Windows) bzw. <b>start.sh</b> (Unix) ausführen. Wie du den Walo-Server, bzw. das Plugin einrichten kannst erfährst du <a href="?article=Konfiguration.php">hier</a>!
</p>