## Allgemeine Informationen

Diese Datenschutzerklärung klärt Sie über die Art, den Umfang und den Zweck der Verarbeitung von personenbezogenen Daten auf unserer Website auf. Personenbezogene Daten sind alle Daten, die auf Sie persönlich beziehbar sind, wie z. B. IP-Adressen, Minecraft-Benutzernamen oder Minecraft-UUIDs.

## Welche Daten wir sammeln

Wir sammeln die folgenden personenbezogenen Daten:

- **Nutzungsdaten:** IP-Adressen, die automatisch vom Webserver beim Zugriff auf die Website erfasst werden.
- **Minecraft-Daten:** Minecraft-Benutzernamen und UUIDs, um Leaderboards zu verwalten und anzuzeigen.

## Zweck der Datenerhebung

Die erhobenen Daten dienen folgenden Zwecken:

- **Nutzungsdaten (IP-Adressen):** Diese Daten werden gesammelt, um die technische Funktionalität der Website zu gewährleisten und aus Sicherheitsgründen.
- **Minecraft-Daten (Benutzernamen und UUIDs):** Diese Daten werden gespeichert, um Ranglisten (Leaderboards) zu erstellen und auf der Website anzuzeigen.

